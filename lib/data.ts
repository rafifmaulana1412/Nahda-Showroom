export const formatPrice = (price: number) =>
  new Intl.NumberFormat("id-ID", {
    style: "currency",
    currency: "IDR",
    maximumFractionDigits: 0,
  }).format(price);

export const formatMileage = (km: number) =>
  km === 0 ? "Baru" : `${new Intl.NumberFormat("id-ID").format(km)} km`;

